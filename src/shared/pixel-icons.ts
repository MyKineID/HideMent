export type IconName = keyof typeof ICONS;

export function pixelIcon(name: IconName, size = 16): string {
  const rows = ICONS[name];
  let rects = "";
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) if (row[x] === "#") rects += `<rect x="${x}" y="${y}" width="1" height="1"/>`;
  });
  return `<svg class="pxi" width="${size}" height="${size}" viewBox="0 0 8 8" shape-rendering="crispEdges" fill="currentColor" aria-hidden="true">${rects}</svg>`;
}

export function hydrateIcons(root: ParentNode = document): void {
  root.querySelectorAll<HTMLElement>("[data-icon]").forEach((el) => {
    el.innerHTML = pixelIcon(el.dataset.icon as IconName, Number(el.dataset.size ?? 16));
  });
}
